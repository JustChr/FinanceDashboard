function SourceHealth({ board }: { board: OfferBoard }) {
  return (
    <Card
      span={12}
      title="Where these numbers came from"
      sub={`Last run ${new Date(board.generatedAt).toLocaleString('en-GB', { dateStyle: 'medium', timeStyle: 'short' })}`}
    >
      <div class="table-wrap">
        <table class="rates compact">
          <thead>
            <tr>
              <th>Provider</th>
              <th>Status</th>
              <th>Page</th>
              <th>Note</th>
            </tr>
          </thead>
          <tbody>
            {board.sources.map((s) => (
              <tr key={s.url}>
                <td class="provider">{s.provider}</td>
                <td>
                  <span class={`badge status-${s.status}`}>{s.status}</span>
                </td>
                <td class="source">
                  <a href={s.url} target="_blank" rel="noreferrer">
                    {new URL(s.url).hostname.replace(/^www\./, '')}
                  </a>
                </td>
                <td class="conditions">{s.note ?? 'All expected rates found'}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <Callout>
        A rate reaches this board only if a probe matched its label on the page <em>and</em> the
        value was plausible for the product. When a bank redesigns its site the probe finds nothing
        and the source shows as <span class="badge status-partial">partial</span> or{' '}
        <span class="badge status-failed">failed</span> — so a broken scrape looks broken rather
        than quietly publishing a wrong number.
      </Callout>
    </Card>
  );
}
