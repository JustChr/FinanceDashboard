import { useMemo } from 'preact/hooks';

import type { DashboardData } from '../lib/data';
import { latest } from '../lib/sdmx';
import {
  bestRate,
  daysSince,
  isStale,
  splitDeposits,
  type Offer,
  type OfferBoard,
} from '../lib/offers';
import { bpsAbs, eur, formatAge, formatTerm, pct } from '../lib/format';
import { Chart, CHART_COLORS, Legend } from '../components/Chart';
import { ladderChart } from '../components/charts';
import { Callout, Card, Stat, StatRow } from '../components/ui';

/**
 * Maps an advertised term onto the MIR maturity band it belongs to, so an
 * advertised rate can be compared against the volume-weighted average for the
 * same kind of money.
 */
const BUCKETS = [
  { label: 'Instant access', mirId: 'dep_on', holds: (m: number | null) => m === null },
  { label: 'Up to 1Y', mirId: 'dep_term_le1', holds: (m: number | null) => m !== null && m <= 12 },
  { label: '1–2Y', mirId: 'dep_term_1_2', holds: (m: number | null) => m !== null && m > 12 && m <= 24 },
  { label: 'Over 2Y', mirId: 'dep_term_2p', holds: (m: number | null) => m !== null && m > 24 },
];

export function Offers({ data }: { data: DashboardData }) {
  const board = data.offers;

  if (!board || board.offers.length === 0) {
    return (
      <div class="grid">
        <Card
          span={12}
          title="Bank offers"
          sub="Advertised rates from published condition pages"
        >
          <Callout>
            No offer board has been published yet. It is generated by the{' '}
            <code>Refresh bank offers</code> workflow, which scrapes each bank&rsquo;s own condition
            page once a day and commits <code>public/data/offers.json</code>. Run it manually from
            the Actions tab to populate this panel.
          </Callout>
        </Card>
      </div>
    );
  }

  return (
    <div class="grid">
      <BestOfBoard data={data} board={board} />
      <AdvertisedVersusConcluded data={data} board={board} />
      <DepositBoard board={board} />
      <LoanBoard board={board} />
      <SourceHealth board={board} />
    </div>
  );
}

/* ------------------------------------------------------------------ */

function BestOfBoard({ data, board }: { data: DashboardData; board: OfferBoard }) {
  const { instant, term } = splitDeposits(board.offers);

  const bestInstant = bestRate(instant, 'deposit');
  const bestTerm = bestRate(term, 'deposit');
  const marketTerm = latest(data.at.get('dep_term'));
  const marketOn = latest(data.at.get('dep_on'));

  const termEdge =
    bestTerm?.rate !== undefined && bestTerm?.rate !== null && marketTerm
      ? bestTerm.rate - marketTerm.value
      : undefined;

  return (
    <Card
      span={5}
      title="The best of what is advertised"
      sub={`${board.offers.length} offers from ${new Set(board.offers.map((o) => o.provider)).size} providers`}
    >
      <StatRow>
        <Stat
          label="Best instant access"
          value={pct(bestInstant?.rate)}
          note={bestInstant?.provider}
          tone="positive"
        />
        <Stat
          label="Best fixed term"
          value={pct(bestTerm?.rate)}
          note={
            bestTerm ? `${bestTerm.provider} · ${formatTerm(bestTerm.termMonths)}` : undefined
          }
          tone="positive"
        />
      </StatRow>
      <StatRow>
        <Stat label="Market average, term" value={pct(marketTerm?.value)} note="ECB MIR, all banks" />
        <Stat label="Market average, overnight" value={pct(marketOn?.value)} note="ECB MIR, all banks" />
      </StatRow>
      <Callout>
        The best advertised term deposit pays <strong>{bpsAbs(termEdge)}</strong>{' '}
        {termEdge !== undefined && termEdge > 0 ? 'above' : 'below'} the volume-weighted average
        Austrian banks actually concluded last month. That difference is what shopping around is
        worth — and the fact that the average sits so far below the best offer is the clearest
        evidence that most savers do not.
      </Callout>
    </Card>
  );
}

/* ------------------------------------------------------------------ */

function AdvertisedVersusConcluded({
  data,
  board,
}: {
  data: DashboardData;
  board: OfferBoard;
}) {
  const rows = useMemo(
    () =>
      BUCKETS.map((bucket) => {
        const candidates = board.offers.filter(
          (o) => o.category === 'deposit' && o.rate !== null && bucket.holds(o.termMonths),
        );
        const best = candidates.reduce<Offer | undefined>(
          (top, o) => (top === undefined || (o.rate ?? 0) > (top.rate ?? 0) ? o : top),
          undefined,
        );
        return {
          label: bucket.label,
          best: best?.rate ?? null,
          provider: best?.provider,
          market: latest(data.at.get(bucket.mirId))?.value ?? null,
        };
      }),
    [board, data],
  );

  const option = useMemo(
    () =>
      ladderChart(
        rows.map((r) => r.label),
        [
          {
            name: 'Best advertised',
            values: rows.map((r) => r.best),
            color: CHART_COLORS.positive,
          },
          {
            name: 'Market average',
            values: rows.map((r) => r.market),
            color: CHART_COLORS.euroArea,
          },
        ],
      ),
    [rows],
  );

  return (
    <Card
      span={7}
      title="Advertised today versus concluded last month"
      sub="Best rate on the board against the ECB volume-weighted average, by maturity"
    >
      <Chart
        option={option}
        height={210}
        ariaLabel="Best advertised Austrian deposit rates compared with ECB average concluded rates by maturity"
      />
      <Legend
        shape="dot"
        items={[
          { label: 'Best advertised', color: CHART_COLORS.positive },
          { label: 'Market average (MIR)', color: CHART_COLORS.euroArea },
        ]}
      />
      <div class="table-wrap">
        <table class="rates compact">
          <thead>
            <tr>
              <th>Maturity</th>
              <th>Best advertised</th>
              <th>Provider</th>
              <th>Market average</th>
              <th>Spread</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.label}>
                <td>{r.label}</td>
                <td class="num">{pct(r.best)}</td>
                <td class="provider">{r.provider ?? '–'}</td>
                <td class="num">{pct(r.market)}</td>
                <td class="num delta up">
                  {r.best !== null && r.market !== null ? bpsAbs(r.best - r.market) : '–'}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <Callout>
        The two series are not the same measurement, and the difference is the point. Green is a
        headline rate a bank is advertising right now, often to new money only. Grey is every euro
        actually placed last month, including the balances that never moved.
      </Callout>
    </Card>
  );
}

