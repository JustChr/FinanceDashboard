function DepositBoard({ board }: { board: OfferBoard }) {
  const { instant, term } = splitDeposits(board.offers);

  return (
    <Card
      span={12}
      title="Savings and term deposit offers"
      sub="Advertised rates, read from each provider's own published condition page"
    >
      <div class="table-wrap">
        <table class="rates">
          <thead>
            <tr>
              <th>Provider</th>
              <th>Product</th>
              <th>Term</th>
              <th>Rate</th>
              <th>Minimum</th>
              <th>Conditions</th>
              <th>Checked</th>
            </tr>
          </thead>
          <tbody>
            <tr class="section-label">
              <td colSpan={7}>Instant access</td>
            </tr>
            {instant.map((o) => (
              <OfferRow key={o.id} offer={o} />
            ))}
            <tr class="section-label">
              <td colSpan={7}>Fixed term</td>
            </tr>
            {term.map((o) => (
              <OfferRow key={o.id} offer={o} />
            ))}
          </tbody>
        </table>
      </div>
      <Callout>
        Rates are shown before Austrian capital gains tax. KESt takes 25% of interest, so a
        headline 3.00% is about 2.25% in hand. Promotional rates that revert after a few months are
        labelled as such — the reverting rate is listed as its own row, because that is what the
        money earns for most of the time it sits there.
      </Callout>
    </Card>
  );
}

function OfferRow({ offer }: { offer: Offer }) {
  const stale = isStale(offer);
  const age = daysSince(offer.observedAt);

  return (
    <tr class={stale ? 'stale' : ''}>
      <td class="provider">{offer.provider}</td>
      <td>{offer.product}</td>
      <td>{formatTerm(offer.termMonths)}</td>
      <td class="num strong">{pct(offer.rate)}</td>
      <td class="num">{offer.amountMin === null ? '–' : eur(offer.amountMin)}</td>
      <td class="conditions">{offer.conditions ?? '–'}</td>
      <td class="source">
        <a href={offer.sourceUrl} target="_blank" rel="noreferrer">
          {formatAge(age)}
        </a>
        {offer.method === 'curated' ? <span class="badge">by hand</span> : null}
      </td>
    </tr>
  );
}

